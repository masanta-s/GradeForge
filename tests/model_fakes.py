def hf(repo, total=None, model_type=None, tags=(), downloads=1000, gated=False):
    entry = {"id": repo, "downloads": downloads, "gated": gated, "tags": list(tags),
             "config": {"model_type": model_type} if model_type else {}}
    if total:
        entry["safetensors"] = {"total": total}
    return entry


