class FakeHF:
    """httpx MockTransport for huggingface.co/api/models; records every request."""

    def __init__(self, repos=HF_REPOS, fail=False):
        self.repos = {r["id"]: r for r in repos}
        self.fail = fail
        self.requests = []

    def __call__(self, request: httpx.Request) -> httpx.Response:
        self.requests.append(request)
        if self.fail:
            raise httpx.ConnectError("offline", request=request)
        path = request.url.path
        if path == "/api/models":
            term = request.url.params["search"].lower().replace("-", "").replace(".", "")
            hits = [r for r in self.repos.values()
                    if term in r["id"].lower().replace("-", "").replace(".", "")]
            return httpx.Response(200, json=sorted(hits, key=lambda r: -r["downloads"]))
        repo = path.removeprefix("/api/models/")
        if repo in self.repos:
            return httpx.Response(200, json=self.repos[repo])
        return httpx.Response(401, json={"error": "Invalid username or password."})

    def client(self) -> httpx.Client:
        return httpx.Client(base_url="https://huggingface.co", transport=httpx.MockTransport(self))


class FakeProbe:
    def __init__(self, identities=(QWEN, GEMMA, TINY)):
        self.identities = {i.name: i for i in identities}
        self.removed, self.pulled = [], []

    def digests(self):
        return {name: f"sha-{name}" for name in self.identities}

    def list_models(self):
        return list(self.identities)

    def probe(self, name):
        if name not in self.identities:
            raise KeyError(name)
        return self.identities[name]

    def show(self, name):
        return {"modelfile": QWEN_MODELFILE}

    def remove(self, name):
        self.removed.append(name)

    def pull(self, name, on_progress=None):
        for done in (0, 50, 100):
            on_progress and on_progress("pulling", done, 100)
        self.pulled.append(name)

